# Give a fully static tc a static util-registration table.
#
# Why this exists: iproute2's tc has NO compiled-in registration table.
# get_qdisc_kind() / get_filter_kind() / get_action_kind() / get_ematch_kind()
# resolve a kind name by (1) walking a cache list, (2) dlopen()ing
# <tc_lib>/q_<kind>.so, then (3) dlsym()ing "<kind>_qdisc_util" from
# dlopen(NULL) — i.e. from the tc binary itself. In a fully static musl build
# dlopen()/dlsym() are link-time stubs that always fail, so every kind falls
# into the "noexist" fallback: a stub util whose parser rejects any option
# ("Unknown qdisc \"netem\", hence option \"delay\" is unparsable") and whose
# printer emits "[Unknown qdisc]". Option-less qdiscs (pfifo_fast) appear to
# work, which is why a `tc -V` smoke check never catches this: the binary is
# static, reports the right version, and is useless for every netem fault.
#
# The utils ARE linked into the binary (tc/Makefile puts all q_*.o/f_*.o/
# m_*.o/em_*.o into TCOBJ); only the lookup path is dead. This script
# generates tc/static_modules.c holding NULL-terminated arrays of every util
# definition found in the source tree, and patches the four get_*_kind()
# functions to consult those arrays before the dlopen/dlsym path.
#
# Usage: run from the iproute2 source root after extraction:
#   /path/to/add-static-register.sh
# Idempotent: regenerates static_modules.c and re-anchors the patches only if
# the anchor lines are still present (a second run is a no-op).

set -eu

cd "$(pwd)"

# ---------------------------------------------------------------- generate --
# Only register utils whose objects actually get linked: m_ipt.o/em_ipt.o/
# em_ipset.o are conditional (TC_CONFIG_XT / xtables) and absent from a
# default build, so globbing m_*.c would emit undefined references. Ask make
# for the final TCMODULES value (conditionals already evaluated against
# config.mk) and derive the file list from that. Run AFTER ./configure.
MODS=$(cd tc && make -pn 2>/dev/null | sed -n 's/^TCMODULES *[:?+]*= *//p' | tail -1)

files_for() { # $1 = prefix (q/f/m/em)
	for m in $MODS; do
		case "$m" in
			$1_*.o) echo "tc/${m%.o}.c" ;;
		esac
	done
}

names() { # $1 = struct type, $2 = object prefix
	grep -h "^struct $1 " $(files_for "$2") | sed 's/^struct [a-z_]*[[:space:]]*\([a-zA-Z0-9_]*\).*/\1/'
}

{
	echo '/* Generated by hack/build-static-tc/add-static-register.sh. */'
	echo '#include <stdio.h>'
	echo '#include <stdlib.h>'
	echo '#include <string.h>'
	echo '#include <sys/socket.h>'
	echo '#include "utils.h"'
	echo '#include "tc_util.h"'
	echo '#include "m_ematch.h"'
	echo
	for n in $(names qdisc_util q); do echo "extern struct qdisc_util $n;"; done
	for n in $(names filter_util f); do echo "extern struct filter_util $n;"; done
	for n in $(names action_util m); do echo "extern struct action_util $n;"; done
	for n in $(names ematch_util em); do echo "extern struct ematch_util $n;"; done
	echo
	echo 'struct qdisc_util *static_qdisc_utils[] = {'
	for n in $(names qdisc_util q); do echo "	&$n,"; done
	echo '	NULL,'
	echo '};'
	echo 'struct filter_util *static_filter_utils[] = {'
	for n in $(names filter_util f); do echo "	&$n,"; done
	echo '	NULL,'
	echo '};'
	echo 'struct action_util *static_action_utils[] = {'
	for n in $(names action_util m); do echo "	&$n,"; done
	echo '	NULL,'
	echo '};'
	echo 'struct ematch_util *static_ematch_utils[] = {'
	for n in $(names ematch_util em); do echo "	&$n,"; done
	echo '	NULL,'
	echo '};'
} > tc/static_modules.c

# ------------------------------------------------------------------ patch ---
# 1) link the new object
grep -q 'static_modules.o' tc/Makefile ||
	sed -i 's/^TCMODULES :=$/TCMODULES :=\nTCMODULES += static_modules.o/' tc/Makefile

# 2) tc.c: externs + static walks in get_qdisc_kind / get_filter_kind
grep -q 'static_qdisc_utils' tc/tc.c || {
	sed -i '/^static struct qdisc_util \*qdisc_list;$/a\
extern struct qdisc_util *static_qdisc_utils[];\
extern struct filter_util *static_filter_utils[];' tc/tc.c
	cat > /tmp/ins_qdisc.txt <<'INSQ'

	{
		struct qdisc_util **sp;

		for (sp = static_qdisc_utils; *sp; sp++)
			if (strcmp((*sp)->id, str) == 0)
				return *sp;
	}
INSQ
	cat > /tmp/ins_filter.txt <<'INSF'

	{
		struct filter_util **sp;

		for (sp = static_filter_utils; *sp; sp++)
			if (strcmp((*sp)->id, str) == 0)
				return *sp;
	}
INSF
	awk -v fqf=/tmp/ins_qdisc.txt -v fff=/tmp/ins_filter.txt '
		BEGIN {
			while ((getline line < fqf) > 0) fq = fq line "\n";
			while ((getline line < fff) > 0) ff = ff line "\n";
		}
		{ print }
		/^[[:space:]]*for \(q = qdisc_list; q; q = q->next\)$/ {
			getline a; print a; getline b; print b; printf "%s", fq
			next
		}
		/^[[:space:]]*for \(q = filter_list; q; q = q->next\)$/ {
			getline a; print a; getline b; print b; printf "%s", ff
			next
		}
	' tc/tc.c > tc/tc.c.new && mv tc/tc.c.new tc/tc.c
}

# 3) m_action.c: extern + static walk in get_action_kind
grep -q 'static_action_utils' tc/m_action.c || {
	sed -i '/^static struct action_util \*get_action_kind(const char \*str)$/i\
extern struct action_util *static_action_utils[];' tc/m_action.c
	cat > /tmp/ins_action.txt <<'INSA'

	{
		struct action_util **sp;

		for (sp = static_action_utils; *sp; sp++)
			if (strcmp((*sp)->id, str) == 0)
				return *sp;
	}
INSA
	awk -v insf=/tmp/ins_action.txt '
		BEGIN { while ((getline line < insf) > 0) ins = ins line "\n"; }
		{ print }
		/^[[:space:]]*for \(a = action_list; a; a = a->next\) \{$/ {
			getline a1; print a1; getline a2; print a2; getline a3; print a3
			printf "%s", ins
			next
		}
	' tc/m_action.c > tc/m_action.c.new && mv tc/m_action.c.new tc/m_action.c
}

# 4) m_ematch.c: extern + static walk in get_ematch_kind (compares ->kind)
grep -q 'static_ematch_utils' tc/m_ematch.c || {
	sed -i '/^static struct ematch_util \*get_ematch_kind(char \*kind)$/i\
extern struct ematch_util *static_ematch_utils[];' tc/m_ematch.c
	cat > /tmp/ins_ematch.txt <<'INSE'

	{
		struct ematch_util **sp;

		for (sp = static_ematch_utils; *sp; sp++)
			if (strcmp((*sp)->kind, kind) == 0)
				return *sp;
	}
INSE
	awk -v insf=/tmp/ins_ematch.txt '
		BEGIN { while ((getline line < insf) > 0) ins = ins line "\n"; }
		{ print }
		/^[[:space:]]*for \(e = ematch_list; e; e = e->next\) \{$/ {
			getline a1; print a1; getline a2; print a2; getline a3; print a3
			printf "%s", ins
			next
		}
	' tc/m_ematch.c > tc/m_ematch.c.new && mv tc/m_ematch.c.new tc/m_ematch.c
}

echo "static registration table: $(grep -c '&.*_util,$' tc/static_modules.c) utils across 4 families"
